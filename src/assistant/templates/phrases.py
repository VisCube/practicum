_WORD = re.compile(r"[а-яё]+", re.IGNORECASE)

# Прощание = вся реплика из этих слов, и хотя бы одно — «ядро»
_BYE_CORE = {"спасибо", "благодарю", "всё", "все", "свидания", "пока", "хватит", "ничего", "нет", "доброго"}
_BYE_FILLER = {"а", "ну", "не", "надо", "нужно", "больше", "до", "ага", "угу", "да", "ок", "хорошо",
               "ладно", "понял", "поняла", "вам", "большое", "тогда", "вопросов", "всего", "и"}

# Приветствие или вызов без содержания: «добрый день», «алло», «это управляющая компания?»
_HELLO = {"здравствуйте", "здрасьте", "здравствуй", "привет", "алло", "алё", "добрый", "доброе",
          "день", "утро", "вечер", "это", "ук", "управляющая", "компания", "девушка", "слышно", "меня"}


def say(key: str, **kwargs: object) -> str:
    """Форматирует фразу из PHRASES по ключу - падает с KeyError если ключ неизвестен"""
    return PHRASES[key].format(**kwargs)


def _words(text: str) -> list[str]:
    """Возвращает список слов в нижнем регистре - только кириллица"""
    return [word.lower() for word in _WORD.findall(text)]


def is_goodbye(text: str) -> bool:
    """Реплика из ≤6 слов с ядром прощания — «спасибо», «всё», «до свидания» и т.д."""
    words = _words(text)
    return (0 < len(words) <= 6
            and any(word in _BYE_CORE for word in words)
            and all(word in _BYE_CORE or word in _BYE_FILLER for word in words))


def is_greeting(text: str) -> bool:
    """Реплика из ≤5 слов - только приветствие без содержательного запроса"""
    words = _words(text)
    return 0 < len(words) <= 5 and all(word in _HELLO for word in words)